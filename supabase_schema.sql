-- 1. Haber tablosunu oluştur
CREATE TABLE IF NOT EXISTS public.news_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link TEXT UNIQUE NOT NULL,
    title TEXT NOT NULL,
    source TEXT NOT NULL,
    category TEXT NOT NULL,
    priority INTEGER DEFAULT 3,
    summary TEXT,
    published_at TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    sent_to_telegram INTEGER DEFAULT 0,
    sent_at TIMESTAMP WITH TIME ZONE
);

-- 2. Hızlı sorgulama, tekilleştirme ve kategori filtreleme indeksleri
CREATE INDEX IF NOT EXISTS idx_news_link ON public.news_items (link);
CREATE INDEX IF NOT EXISTS idx_news_sent ON public.news_items (sent_to_telegram, category, priority);
CREATE INDEX IF NOT EXISTS idx_news_created ON public.news_items (created_at DESC);

-- 3. Row Level Security (RLS) Ayarı
ALTER TABLE public.news_items ENABLE ROW LEVEL SECURITY;

-- 4. Hem anon key hem de service_role key ile okuma/yazma politikası
DROP POLICY IF EXISTS "Bot Full Access Policy" ON public.news_items;
CREATE POLICY "Bot Full Access Policy" ON public.news_items
    FOR ALL
    TO anon, authenticated, service_role
    USING (true)
    WITH CHECK (true);
